// Customer Master / Supplier Master were retired in favor of Business
// Partner (filtered by partnerType Customer/Vendor) — see BUGLOG. Every page
// that used to read customerApi/supplierApi only ever called `.useList()`
// with no arguments to populate a dropdown or a lookup map, so rather than
// touch each of those ~45 call sites individually, customerApi/supplierApi
// are kept as adapters: same `.useList()` shape, backed by
// GET /business-partners?partnerType=..., with each row's fields aliased
// back to the old Customer/Supplier field names (customerCode/customerName,
// supplierCode/supplierName, phone, ...) alongside the native Business
// Partner ones. Fields the old masters had that Business Partner does not
// (discount %, price list, GSTIN/PAN, city/state, supplier bank details,
// customer/supplier "group") are NOT aliased — callers that read those now
// get undefined, by design (see the field-gap audit in BUGLOG).
//
// create/update/delete are deliberately not exposed here — Customer Master/
// Supplier Master are gone, so nothing outside this adapter should be
// writing through the old shape; Business Partner's own page is the only
// place these records are created or edited now.
function formatLegacyPartnerAddress(addr) {
  if (!addr) return '';
  // addressName (the Business Partner Address tab's own "Address Name *"
  // field) was missing from this line entirely -- every page-local
  // formatBusinessPartnerAddress (Sales Order/Invoice/Quotation/Credit
  // Memo/Return, Delivery Challan, Purchase Order/GRN/Credit Memo) leads
  // with it, but this shared adapter (what customerApi/supplierApi's
  // .billingAddress/.shippingAddress actually come from -- see
  // toLegacyPartnerShape below) silently dropped it. That's what "ship to a
  // different customer" picks its address from, so the customer's own
  // Billing/Shipping Address name never made it into the document.
  // Standard order (lib/addressFormat.js), no double commas.
  return partnerAddressLines(addr).join('\n');
}

function toLegacyPartnerShape(p) {
  // Sales/Purchase forms (Sales Quotation, Sales Order, Sales Invoice,
  // Delivery Challan, Enquiry, Purchase Order/Quotation, ...) all auto-fill
  // their own Contact Person/Phone/Email fields from whatever this adapter
  // hands back for a picked customer/vendor. When the partner has a Contact
  // Person marked "Set as default" on the Business Partner form, that
  // person's own details are what should land there — not just the
  // partner's own top-level phone/email, which is what "the first contact"
  // effectively meant before isDefault existed.
  //
  // Falls back to the first contact row when none is marked default: a
  // partner with exactly one contact is the common case, and nothing forces
  // that lone row to be explicitly flagged "Default" — without this fallback
  // it (and every document's Contact Person auto-fill) silently stayed blank
  // even though the contact was right there.
  const defaultContact = Array.isArray(p.contacts) && p.contacts.length
    ? (p.contacts.find((c) => c.isDefault) || p.contacts[0])
    : null;
  const defaultContactName = defaultContact
    ? [defaultContact.firstName, defaultContact.lastName].filter(Boolean).join(' ')
    : '';

  const billingAddr = Array.isArray(p.addresses)
    ? (p.addresses.find((a) => a.addressType === 'Billing' && a.isDefault)
       || p.addresses.find((a) => a.addressType === 'Billing')
       || p.addresses.find((a) => a.isDefault)
       || p.addresses[0])
    : null;
  const shippingAddr = Array.isArray(p.addresses)
    ? (p.addresses.find((a) => a.addressType === 'Shipping' && a.isDefault)
       || p.addresses.find((a) => a.addressType === 'Shipping')
       || billingAddr)
    : null;

  const gstin = billingAddr?.gstNumber || shippingAddr?.gstNumber || p.gstin || p.gstNumber || '';
  const gstRegistrationType = billingAddr?.gstType || shippingAddr?.gstType || p.gstRegistrationType || p.gstType || 'Regular/TDS/ISD';

  return {
    ...p,
    customerCode: p.partnerCode,
    customerName: p.partnerName,
    supplierCode: p.partnerCode,
    supplierName: p.partnerName,
    phone: defaultContact?.mobile || defaultContact?.telephone || p.mobile || p.telephone || '',
    email: defaultContact?.email || p.email || '',
    contactPerson: p.contactPerson || defaultContactName,
    notes: p.remarks || '',
    // Business Partner's currency is "which currencies this partner deals
    // in" (BP_CURRENCY_OPTIONS: All/INR/USD/EUR/GBP, default 'All') — a
    // different thing from a document's own currency code. Several sales/
    // purchase forms do `setValue('currency', found.currency || 'INR')` when
    // a customer/supplier is picked, expecting a real code or nothing; 'All'
    // would pass that `||` (it's truthy) and get written onto the document
    // as an invalid currency. Only forward it when it names an actual
    // currency, so the existing fallback to 'INR' still applies otherwise.
    currency: p.currency && p.currency !== 'All' ? p.currency : undefined,
    billingAddress: p.billingAddress || formatLegacyPartnerAddress(billingAddr),
    shippingAddress: p.shippingAddress || formatLegacyPartnerAddress(shippingAddr),
    state: p.state || billingAddr?.state || shippingAddr?.state || '',
    city: p.city || billingAddr?.city || shippingAddr?.city || '',
    gstin,
    gstNumber: gstin,
    gstRegistrationType,
    gstType: gstRegistrationType,
  };
}

function makeLegacyPartnerApi(partnerType) {
  return {
    // Defaults to the server's slim `?view=picker` projection (id/code/name/
    // mobile/telephone/email/contactPerson/remarks/currency/status/
    // paymentTerms + a trimmed contacts/addresses select — see
    // businessPartnerPickerSelect in backend/src/routes/resources.js,
    // audited field-by-field against every customerApi/supplierApi
    // consumer). A caller passing its own `view` (or `undefined` to force
    // the full row) still wins — `params` is spread after `view` on purpose.
    useList: (params) => {
      const query = { view: 'picker', ...(params || {}), partnerType };
      const result = businessPartnerApi.useList(query);
      const data = useMemo(
        () => (result.data ? result.data.map(toLegacyPartnerShape) : result.data),
        [result.data]
      );
      return { ...result, data };
    },
  };
}
