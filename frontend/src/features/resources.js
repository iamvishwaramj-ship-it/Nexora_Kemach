// Notification bell — hand-injected rather than generated by createCrudApi:
// this is scoped to the current user (no id-based CRUD) and two of its four
// endpoints (approve/reject) act on an existing record with no body, same
// reasoning as journalEntryPostApi above.
//
// The list is kept fresh WITHOUT refetching: real-time socket events carry
// their data and are spliced into this cache by lib/useNotificationSocket.js,
// and the three mutations below patch the affected row locally on success
// (instead of invalidating the list, which would cost a GET per click). Both
// patch the cache entry for the `undefined` arg, the exact arg Header.jsx
// queries with.
const patchNotification = (draft, id, changes) => {
  const row = draft.data.find((n) => n.id === id);
  if (!row) return;
  if (row.status === 'Unread' && changes.status === 'Read') draft.unreadCount = Math.max(0, (draft.unreadCount || 0) - 1);
  Object.assign(row, changes);
};
const patchOnSuccess = (changes) => async (id, { dispatch, queryFulfilled }) => {
  try {
    const { data } = await queryFulfilled;
    // An orphaned request resolves as a normal success but comes back
    // 'Cancelled' (see resolveApproval) -- show that, not the clicked decision.
    const applied = changes.actionStatus && data?.actionStatus === 'Cancelled' ? { ...changes, actionStatus: 'Cancelled' } : changes;
    dispatch(notificationApi.util.updateQueryData('getNotifications', undefined, (draft) => patchNotification(draft, id, applied)));
  } catch {
    // A failed mutation changes nothing; the caller surfaces the error.
  }
};

