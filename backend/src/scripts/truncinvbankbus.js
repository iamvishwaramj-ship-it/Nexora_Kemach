/**
 * truncinvbankbus.js — empties every transaction table behind the
 * Inventory, Banking, Purchase, and Sales menus (navConfig.js), including
 * their currently-hidden sub-menu items (Enquiry, Follow-up, Cheque Print).
 *
 *   npm run truncinvbankbus -- --yes
 *
 * DESTRUCTIVE AND IRREVERSIBLE. Without --yes it only prints what it would
 * delete and exits, matching src/scripts/empdepttrnck.js's own guard.
 *
 * ---------------------------------------------------------------------------
 * What's covered
 * ---------------------------------------------------------------------------
 * Inventory  : Stock Receipt, Stock Issue, Stock Adjustment,
 *              Stock Transfer (Request / Issue / Receipt)
 * Banking    : Deposit Entry, Bank Reconciliation, Cheque Print (hidden),
 *              Payment Receipt, Payment Voucher
 * Purchase   : Purchase Quotation, Purchase Order, Purchase GRN,
 *              Purchase Return, Purchase Invoice, Purchase Credit Memo
 * Sales      : Enquiry (hidden), Follow-up (hidden), Sales Quotation,
 *              Sales Order, Delivery Challan, Sales Return, Sales Invoice,
 *              Sales Credit Memo
 *
 * Plus three tables that are *generated by* those documents rather than
 * being a menu item themselves — left in place they'd reference documents
 * that no longer exist, so they're wiped alongside the documents that fed
 * them:
 *   - Stock                (the stock ledger — every Inventory/Purchase/
 *                            Sales posting above writes rows here)
 *   - CustomerOutstanding  (balance snapshots created by Sales Invoice)
 *   - SupplierOutstanding  (balance snapshots created by Purchase Invoice)
 *
 * Deliberately NOT touched: Collection Entry / Payment Entry and their
 * application tables (collections, supplier_payments, ...). Those live
 * under the separate, hidden Receivables/Payables menus — not Inventory,
 * Banking, Purchase, or Sales — and they're real documents a user entered,
 * not a derived summary. They only ever reference an invoice by its plain
 * text invoiceNo (no foreign key), so deleting the invoices above does not
 * touch them and does not break anything for them to keep existing.
 * Document Numbering (document_numbering) is also left alone on purpose —
 * it's configuration (prefixes, series, next-number counters), not
 * transaction data, and resetting it is a separate decision.
 *
 * ---------------------------------------------------------------------------
 * One table at a time, not batched
 * ---------------------------------------------------------------------------
 * Both the dry-run counts and the actual deletes run strictly one table at
 * a time (a plain sequential loop, not Promise.all / a single
 * multi-table $transaction) — this server can't take 51 queries or a
 * giant transaction spanning every table at once. Each table is fully
 * finished (counted, or deleted + identity reset) before the next one
 * starts, at the cost of the all-or-nothing guarantee one big transaction
 * would have given: if the run is interrupted partway through the delete
 * phase, whatever printed above tells you exactly where it stopped, and
 * re-running the script is safe — an already-emptied table just counts 0
 * and does nothing more.
 *
 * ---------------------------------------------------------------------------
 * Why DELETE + DBCC CHECKIDENT rather than an actual TRUNCATE TABLE
 * ---------------------------------------------------------------------------
 * Same reason as empdepttrnck.js: SQL Server refuses TRUNCATE TABLE on any
 * table with an identity column that's still non-empty in a way SQL Server
 * won't just let you TRUNCATE if the schema evolves a new FK onto one of
 * these later, and several of these already are FK targets in one direction
 * or another. DELETE never runs into that, and DBCC CHECKIDENT(RESEED, 0)
 * supplies the identity reset that DELETE alone doesn't do — together they
 * reproduce TRUNCATE's end state (next inserted row gets id 1 again).
 *
 * Order matters within each document type — every *Item child table is
 * deleted before its header — and Follow-up is deleted before Enquiry
 * because follow_ups.enquiry_id -> enquiries.id is NO ACTION (not CASCADE):
 * see the comment on FollowUp.enquiry in schema.prisma. Everything else
 * here links to other documents by plain text (invoice/PO/DO number), not
 * a real foreign key, so there's no other ordering constraint between the
 * groups themselves.
 */
