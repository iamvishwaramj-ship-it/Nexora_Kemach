// Identity reset. Kept separate from the deletes: it's the cosmetic half of
// the job, so a database where DBCC is not permitted (a restricted login)
// still gets every row deleted rather than failing the whole run.
async function reseed(table) {
  try {
    await prisma.$executeRawUnsafe(`DBCC CHECKIDENT ('[dbo].[${table}]', RESEED, 0) WITH NO_INFOMSGS`);
    return true;
  } catch (err) {
    console.warn(`  ! could not reset the identity counter on ${table}: ${err.message}`);
    return false;
  }
}

async function run() {
  const confirmed = process.argv.includes('--yes');

  // --- Dry-run counts, one table at a time -------------------------------
  // Deliberately NOT Promise.all — firing 51 count() queries at once opens
  // up to 51 simultaneous connections, which is more than this server
  // handles comfortably (see connection_limit in DATABASE_URL). Counting
  // one table, waiting for it to finish, then moving to the next keeps the
  // load on the DB down to a single query in flight at any moment.
  console.log('Inventory / Banking / Purchase / Sales — truncate all sub-menu tables');
  console.log('----------------------------------------------------------------------');
  const counts = [];
  let currentGroup = null;
  for (const t of TARGETS) {
    // eslint-disable-next-line no-await-in-loop -- intentional: see comment above.
    const c = await prisma[t.model].count();
    counts.push(c);
    if (t.group !== currentGroup) {
      currentGroup = t.group;
      console.log(`\n${currentGroup}:`);
    }
    console.log(`  ${t.label.padEnd(32)} (${t.table.padEnd(32)}) : ${c} row(s)`);
  }
  const total = counts.reduce((sum, c) => sum + c, 0);
  console.log(`\nTotal: ${total} row(s) across ${TARGETS.length} table(s)`);
  console.log('');

  if (!confirmed) {
    console.error('Nothing has been changed — this is a dry run.');
    console.error('Re-run with:  npm run truncinvbankbus -- --yes');
    process.exitCode = 1;
    return;
  }

  if (total === 0) {
    console.log('All target tables are already empty — nothing to delete.');
    return;
  }

  console.log('Deleting — one table at a time, this cannot be undone...');
  console.log('');

  // --- Delete + reseed, one table at a time, fully sequential ------------
  // No single transaction spanning all 51 tables either, for the same
  // reason as the counts above — a lighter, one-table-at-a-time footprint
  // matters more here than the all-or-nothing guarantee a giant transaction
  // would give. Each table is fully finished (deleted AND its identity
  // reset) before the next one starts, so a table is never left counted-but-
  // not-yet-cleared for long, and if the run is interrupted partway, the
  // console output above tells you exactly which table it stopped on —
  // re-running the script picks up cleanly, since every already-emptied
  // table just reports 0 rows and does nothing on its next pass.
  for (const t of TARGETS) {
    // eslint-disable-next-line no-await-in-loop -- intentional: see comment above.
    const r = await prisma[t.model].deleteMany({});
    if (r.count) console.log(`  deleted   ${r.count} row(s) from ${t.label}`);
    // eslint-disable-next-line no-await-in-loop -- intentional: see comment above.
    await reseed(t.table);
  }

  console.log('');
  console.log('Done. Every Inventory / Banking / Purchase / Sales document table (plus');
  console.log('the Stock ledger and Customer/Supplier Outstanding) is empty and its ids');
  console.log('restart at 1.');
  console.log('');
  console.log('Note: Document Numbering (Company > Document Numbering) was left alone —');
  console.log('  its series counters still continue from wherever they were.');
  console.log('Note: Collection Entry / Payment Entry (Receivables/Payables) were left');
  console.log('  alone — they are separate documents, not part of these four menus.');
}

run()
  .catch((err) => {
    console.error('Truncate error:', err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
